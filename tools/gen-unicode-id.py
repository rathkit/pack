#!/usr/bin/env python3
"""Generates src/unicode.rs: ID_Start and ID_Continue range tables.

Uses only the Python standard library (`unicodedata`), so the generated Rust file keeps the
crate dependency-free. Re-run with a newer Python to move to a newer Unicode version:

    python3 tools/gen-unicode-id.py > src/unicode.rs

Definitions (UAX #31, as used by ECMAScript):
  ID_Start    = Lu Ll Lt Lm Lo Nl + Other_ID_Start
  ID_Continue = ID_Start + Mn Mc Nd Pc + Other_ID_Continue
Pattern_Syntax and Pattern_White_Space are excluded by the standard, but none of the
characters above overlap them, so no subtraction is needed.
"""
import sys
import unicodedata

START_CATEGORIES = {"Lu", "Ll", "Lt", "Lm", "Lo", "Nl"}
CONTINUE_EXTRA_CATEGORIES = {"Mn", "Mc", "Nd", "Pc"}
OTHER_ID_START = [0x1885, 0x1886, 0x2118, 0x212E, 0x309B, 0x309C]
# U+30FB and U+FF65 joined ID_Continue in Unicode 15.1.
OTHER_ID_CONTINUE = [0x00B7, 0x0387, *range(0x1369, 0x1372), 0x19DA, 0x30FB, 0xFF65]


def ranges(predicate):
    out, start = [], None
    for cp in range(0x110000):
        # Surrogates are not scalar values; Rust `char` cannot hold them.
        inside = not (0xD800 <= cp <= 0xDFFF) and predicate(cp)
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def is_start(cp):
    return unicodedata.category(chr(cp)) in START_CATEGORIES or cp in OTHER_ID_START


def is_continue(cp):
    return (
        is_start(cp)
        or unicodedata.category(chr(cp)) in CONTINUE_EXTRA_CATEGORIES
        or cp in OTHER_ID_CONTINUE
    )


def emit(name, table):
    print(f"static {name}: [(u32, u32); {len(table)}] = [")
    line = "   "
    for lo, hi in table:
        item = f" (0x{lo:X}, 0x{hi:X}),"
        if len(line) + len(item) > 100:
            print(line)
            line = "   "
        line += item
    print(line)
    print("];\n")


print("// @generated by tools/gen-unicode-id.py. Do not edit by hand.")
print(f"//! Unicode {unicodedata.unidata_version} identifier tables (ID_Start and ID_Continue).\n")
print("pub fn is_id_start(c: char) -> bool {")
print("    in_table(&ID_START, c as u32)")
print("}\n")
print("pub fn is_id_continue(c: char) -> bool {")
print("    in_table(&ID_CONTINUE, c as u32)")
print("}\n")
print("fn in_table(table: &[(u32, u32)], cp: u32) -> bool {")
print("    let i = table.partition_point(|&(_, hi)| hi < cp);")
print("    table.get(i).is_some_and(|&(lo, _)| lo <= cp)")
print("}\n")
emit("ID_START", ranges(is_start))
emit("ID_CONTINUE", ranges(is_continue))
