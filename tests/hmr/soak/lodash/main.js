import * as _ from 'lodash-es';
import { chunk, groupBy, sortBy, uniqBy, merge, cloneDeep, camelCase, kebabCase, template, get, set, debounce, memoize, isEqual, difference, zipObject, flattenDeep, pick, omit, range, shuffle, sample, throttle } from 'lodash-es';

const log = [];
const out = (label, value) => log.push(label + ' ' + JSON.stringify(value));
const people = [{ name: 'ann', age: 30, tags: ['a', 'b'] }, { name: 'bob', age: 25, tags: ['b'] }, { name: 'cy', age: 30, tags: [] }];
out('chunk', chunk([1, 2, 3, 4, 5], 2));
out('groupBy', groupBy(people, 'age'));
out('sortBy', sortBy(people, ['age', 'name']).map((p) => p.name));
out('uniqBy', uniqBy(people, 'age').length);
out('merge', merge({ a: { b: 1 }, c: [1] }, { a: { d: 2 }, c: [2, 3] }));
const deep = cloneDeep({ a: [1, { b: 2 }], d: new Date(0) });
out('cloneDeep', [deep.a[1].b, deep.d.getTime()]);
out('case', [camelCase('foo bar-baz'), kebabCase('FooBar baz')]);
out('template', template('hello <%= user %>, <% _.forEach(items, function (i) { %>[<%- i %>]<% }); %>')({ user: 'ann', items: ['<a>', 'b'], _ }));
const target = {};
set(target, 'x.y[0].z', 5);
out('get/set', [get(target, 'x.y[0].z'), get(target, 'nope', 'dflt'), target]);
out('isEqual', [isEqual({ a: [1, { b: 2 }] }, { a: [1, { b: 2 }] }), isEqual([1], [2])]);
out('misc', [difference([1, 2, 3], [2]), zipObject(['a', 'b'], [1, 2]), flattenDeep([1, [2, [3, [4]]]]), pick({ a: 1, b: 2 }, ['a']), omit({ a: 1, b: 2 }, ['a']), range(0, 10, 3)]);
const calls = [];
const memo = memoize((n) => (calls.push(n), n * 2));
memo(2); memo(2); memo(3);
out('memoize', calls);
out('shuffle', [shuffle([1, 2, 3]).length, [1, 2, 3].includes(sample([1, 2, 3]))]);
out('all', Object.keys(_).length > 300);
let debounced = 0;
const d = debounce(() => debounced++, 5);
d(); d(); d();
await new Promise((r) => setTimeout(r, 30));
out('debounce', debounced);
const t = throttle(() => 1, 10);
out('throttle', typeof t);
console.log(log.join('\n'));
