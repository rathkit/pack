import * as THREE from 'three';
import { Vector3, Matrix4, Quaternion, Euler, Box3, Color, MathUtils, Object3D, Mesh, BoxGeometry, MeshBasicMaterial, Scene, PerspectiveCamera, Group } from 'three';

const log = [];
const round = (v) => JSON.parse(JSON.stringify(v, (k, x) => (typeof x === 'number' ? Math.round(x * 1e4) / 1e4 : x)));
const out = (label, value) => log.push(label + ' ' + JSON.stringify(round(value)));
const v = new Vector3(1, 2, 3);
out('vector', [v.length(), v.clone().normalize().toArray(), v.clone().cross(new Vector3(0, 1, 0)).toArray(), v.dot(new Vector3(1, 1, 1))]);
const m = new Matrix4().makeRotationY(Math.PI / 2).setPosition(1, 0, 0);
out('matrix', [v.clone().applyMatrix4(m).toArray(), m.determinant(), new Matrix4().copy(m).invert().elements.slice(0, 4)]);
const q = new Quaternion().setFromEuler(new Euler(0.1, 0.2, 0.3, 'XYZ'));
out('quaternion', [q.toArray(), new Euler().setFromQuaternion(q).toArray().slice(0, 3)]);
const box = new Box3().setFromPoints([new Vector3(0, 0, 0), new Vector3(2, 3, 4)]);
out('box', [box.getSize(new Vector3()).toArray(), box.containsPoint(new Vector3(1, 1, 1))]);
out('color', [new Color('#ff8000').getHex(), new Color(0.5, 0.25, 0).getHexString(), new Color().setHSL(0.5, 1, 0.5).toArray()]);
out('math', [MathUtils.clamp(5, 0, 3), MathUtils.degToRad(180), MathUtils.lerp(0, 10, 0.3), MathUtils.isPowerOfTwo(64)]);
const scene = new Scene();
const group = new Group();
const mesh = new Mesh(new BoxGeometry(1, 2, 3), new MeshBasicMaterial({ color: 0xff0000 }));
mesh.position.set(1, 2, 3);
group.add(mesh);
group.rotation.y = Math.PI / 2;
scene.add(group);
scene.updateMatrixWorld(true);
out('scene', [mesh.getWorldPosition(new Vector3()).toArray(), mesh.geometry.attributes.position.count, scene.children.length, mesh.geometry.boundingBox === null]);
mesh.geometry.computeBoundingBox();
out('geometry', [mesh.geometry.boundingBox.getSize(new Vector3()).toArray(), mesh.geometry.index.count]);
const camera = new PerspectiveCamera(60, 2, 0.1, 100);
camera.position.set(0, 0, 5);
camera.lookAt(0, 0, 0);
camera.updateMatrixWorld();
out('camera', [camera.projectionMatrix.elements.slice(0, 2), new Vector3(0, 0, 0).project(camera).toArray()]);
out('all', [Object.keys(THREE).length > 400, typeof THREE.REVISION]);
console.log(log.join('\n'));
